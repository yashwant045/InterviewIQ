"""
InterviewIQ AI Service - Pydantic Schemas
Enforces strict structured JSON outputs from LLMs (OpenAI, Gemini).
"""

from typing import List, Optional, Any, Union
from pydantic import BaseModel, Field, ConfigDict


# ==========================================
# 1. Interview Context & Questions
# ==========================================

class InterviewContext(BaseModel):
    """Context required to configure and generate tailored interview questions."""
    model_config = ConfigDict(populate_by_name=True)

    role: str = Field(..., description="Target candidate role, e.g. 'Senior Full Stack Engineer'")
    company: str = Field(..., description="Target company, e.g. 'Google', 'Netflix'")
    difficulty: str = Field("Senior", description="Seniority level: Junior, Mid-Level, Senior, Lead")
    parsed_resume_skills: List[str] = Field(
        default_factory=list,
        description="List of detected technical and behavioral skills from the candidate's resume"
    )


class GeneratedQuestion(BaseModel):
    """Structured question output generated by the LLM."""
    model_config = ConfigDict(populate_by_name=True)

    question_text: str = Field(..., description="Clear and targeted interview question text")
    topic: str = Field(..., description="Domain topic or competency being evaluated")
    expected_ideal_answer: str = Field(
        ...,
        description="Exemplary benchmark answer outlining architecture, algorithms, and trade-offs"
    )
    requires_code: bool = Field(
        default=False,
        description="Whether this question involves a live coding implementation"
    )
    is_followup: bool = Field(
        default=False,
        description="Whether this question is an adaptive follow-up"
    )
    starter_code: Optional[str] = Field(
        default=None,
        description="Optional starter code template for coding questions"
    )


class GeneratedQuestionList(BaseModel):
    """Container for batch generation of questions with structured outputs."""
    questions: List[GeneratedQuestion] = Field(..., description="List of generated questions")


# ==========================================
# 2. Answer Evaluation & Feedback
# ==========================================

class AnswerEvaluation(BaseModel):
    """Granular comparative evaluation of candidate's response against the ideal solution."""
    model_config = ConfigDict(populate_by_name=True)

    technical_score: float = Field(
        ...,
        ge=0.0,
        le=100.0,
        description="Technical depth and accuracy score between 0 and 100"
    )
    communication_score: float = Field(
        ...,
        ge=0.0,
        le=100.0,
        description="Articulation, structure, and STAR methodology score between 0 and 100"
    )
    feedback: str = Field(..., description="Constructive feedback comparing answer against model solution")
    missing_keywords: List[str] = Field(
        default_factory=list,
        description="Key technical terms or architectural concepts omitted by the candidate"
    )
    needs_followup: bool = Field(
        default=False,
        description="Whether a clarifying or deeper follow-up question is warranted"
    )
    followup_question: Optional[str] = Field(
        default=None,
        description="Adaptive follow-up question if needs_followup is true"
    )


# ==========================================
# 3. Radar & Workmap Competencies
# ==========================================

class RadarScores(BaseModel):
    """6-axis video and behavioral performance radar dimensions (0-100)."""
    model_config = ConfigDict(populate_by_name=True)

    Professionalism: float = Field(ge=0.0, le=100.0, description="Demeanor, composure, and professional ethics")
    Attitude: float = Field(ge=0.0, le=100.0, description="Enthusiasm, coachability, and growth mindset")
    Creativity: float = Field(ge=0.0, le=100.0, description="Novel problem solving and architectural ingenuity")
    Communication: float = Field(ge=0.0, le=100.0, description="Verbal articulation, brevity, and structure")
    Leadership: float = Field(ge=0.0, le=100.0, description="Ownership, initiative, and decision making")
    Teamwork: float = Field(ge=0.0, le=100.0, description="Collaboration, cross-functional empathy, and consensus building")


class WorkmapScores(BaseModel):
    """4-pillar workplace execution competency bars (0-100)."""
    model_config = ConfigDict(populate_by_name=True)

    Presentation: float = Field(ge=0.0, le=100.0, description="Impactful communication and structured delivery")
    Opportunistic: float = Field(ge=0.0, le=100.0, description="Agility, identifying leverage, and rapid iteration")
    Business_Acumen: float = Field(
        ge=0.0,
        le=100.0,
        alias="Business Acumen",
        description="Understanding business ROI, customer impact, and trade-offs"
    )
    Closing_Technique: float = Field(
        ge=0.0,
        le=100.0,
        alias="Closing Technique",
        description="Decisiveness, summarization, and action-oriented conclusions"
    )


# ==========================================
# 4. Final Comprehensive Interview Report
# ==========================================

class InterviewReport(BaseModel):
    """Complete post-interview debrief and performance synthesis."""
    model_config = ConfigDict(populate_by_name=True)

    overall_score: float = Field(ge=0.0, le=100.0, description="Overall aggregate interview score (0-100)")
    strengths: List[str] = Field(..., description="Key technical and behavioral competencies demonstrated")
    weaknesses: List[str] = Field(..., description="Identified growth areas and gaps")
    radar_scores: RadarScores = Field(..., description="6-axis performance radar evaluation")
    workmap_scores: WorkmapScores = Field(..., description="4-pillar workplace competency mapping")
    actionable_feedback: str = Field(..., description="Personalized roadmap and specific practice recommendations")


# ==========================================
# 5. Route Integration Models (Backwards-Compatible Adapters)
# ==========================================

class QuestionItem(BaseModel):
    order_index: int
    question_text: str
    topic: str
    difficulty: str
    type: str = "technical"
    starter_code: Optional[str] = None
    ideal_answer: Optional[str] = None

class GenerateQuestionsRequest(BaseModel):
    role: str = Field(..., example="Senior Full Stack Engineer")
    company: str = Field(..., example="Google")
    difficulty: str = Field(..., example="Senior")
    type: str = Field("Technical", example="Technical")
    skills: List[str] = Field(default_factory=list)
    resumeText: Optional[str] = None
    count: int = Field(3, ge=1, le=10)

class GenerateQuestionsResponse(BaseModel):
    role: str
    company: str
    difficulty: str
    questions: List[QuestionItem]

class EvaluateAnswerRequest(BaseModel):
    role: str
    company: str
    question_text: str
    answer: str
    code_submitted: Optional[str] = None
    difficulty: str = "Mid-Level"
    ideal_answer: Optional[str] = None

class RadarAdjustments(BaseModel):
    professionalism: float
    attitude: float
    creativity: float
    communication: float
    leadership: float
    teamwork: float

class EvaluateAnswerResponse(BaseModel):
    score: float
    feedback: str
    follow_up_question: Optional[str] = None
    radar_adjustments: RadarAdjustments
    workmap_scores: Any

class AnswerPair(BaseModel):
    question: str
    answer: str
    score: float

class GenerateReportRequest(BaseModel):
    role: str
    company: str
    difficulty: str
    answers: List[AnswerPair]

class GenerateReportResponse(BaseModel):
    overall_score: float
    technical_score: float
    communication_score: float
    strengths: List[str]
    weaknesses: List[str]
    recommendations: List[str]
    detailed_summary: str
    radar: RadarAdjustments
    workmap: Any
